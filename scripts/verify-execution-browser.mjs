import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {mkdtemp,readFile,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {launchBrowser} from './lib/shellFixtures.mjs';
const repo=fileURLToPath(new URL('..',import.meta.url)),output=await mkdtemp(join(tmpdir(),'execution-browser-'));
const bundlePath=join(output,'harness.js');
await build({entryPoints:[`${repo}/web/test/browser/execution.browser.tsx`],outfile:bundlePath,bundle:true,jsx:'automatic',define:{'process.env.NEXT_PUBLIC_AGENT_SERVER_URL':JSON.stringify('http://fixture.invalid')},tsconfig:`${repo}/web/tsconfig.json`,plugins:[{
  name:'isolated-console',setup(build){build.onLoad({filter:/\/web\/lib\/agentConsole\.tsx$/},()=>({loader:'js',contents:`export function useAgentConsole(){return {providers:[{id:'codex',label:'Codex',available:true,model:null,models:[]}],runs:[],connection:'open',startRun(){window.manualRunRequests++;return true;}}}` }));}
}]});
const bundle=await readFile(bundlePath,'utf8');
const {compile}=await import(`${repo}/node_modules/@tailwindcss/node/dist/index.mjs`);
const compiler=await compile(await readFile(`${repo}/web/app/globals.css`,'utf8'),{base:`${repo}/web/app`,onDependency(){}});
const candidates=[...bundle.matchAll(/"([^"\n]{1,500})"/g)].flatMap(m=>m[1].split(/\s+/)).filter(c=>/^[\w:[\]#()./%!-]+$/.test(c));
const path=join(output,'harness.html');
await writeFile(path,`<html><head><meta name="viewport" content="width=device-width,initial-scale=1"><style>${compiler.build(candidates)}body{margin:0;background:var(--color-surface-0);color:var(--color-fg);font-family:Arial}</style></head><body><div id="root"></div><script>${bundle.replaceAll('</script','<\\/script')}</script></body></html>`);
const browser=await launchBrowser();
try {
  const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(pathToFileURL(path).href);
  await page.getByText('Deferred verification: business',{exact:true}).waitFor();
  assert.equal(await page.getByText('1/2 units accepted · 4/6 attempts accounted',{exact:true}).count(),1);
  await page.getByRole('button',{name:'delivered',exact:true}).click();
  await page.getByText('Verified delivery',{exact:false}).first().waitFor();
  assert.equal(await page.getByText('Deferred verification: business',{exact:true}).count(),0);
  await page.getByRole('button',{name:'exhausted',exact:true}).click();
  const controls=page.getByRole('region',{name:'Pipeline status',exact:true});
  await controls.getByText('Allowance exhausted',{exact:true}).waitFor();
  assert.equal(await controls.getByRole('button',{name:/Resume|Recover/}).count(),0);
  await controls.getByText(/approve a new allocation before restarting/).waitFor();
  await page.getByRole('status').waitFor();
  assert.match(await page.getByRole('status').textContent(),/checkpoint.*preserved/);
  await page.getByRole('button',{name:/Budget exhausted · 1 units accepted/}).waitFor();
  await page.getByText('Plan and decision history',{exact:true}).click();
  await page.getByText(/Changed strategy after failed ownership check/).waitFor();
  for(const width of [1280,375]) {
    await page.setViewportSize({width,height:900});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`overflow at ${width}`);
    assert.ok((await controls.boundingBox()).height<600,`budget explanation becomes an unreadable narrow column at ${width}`);
    await page.screenshot({path:join(output,`execution-${width}.png`),fullPage:true});
  }
  const allocation=page.getByRole('region',{name:'Autonomous execution'});
  await page.getByRole('button',{name:'Run S1-02',exact:true}).click();
  await page.waitForFunction(()=>window.pipelineRunRequests===1);
  assert.equal(await page.getByText('Started S1-02',{exact:true}).count(),0);
  assert.equal(await page.getByText('Pipeline is running',{exact:true}).count(),0,'sending a request cannot announce success');
  await page.evaluate(()=>window.resolvePipelineStart());
  await page.getByText('That did not fully work',{exact:true}).waitFor();
  assert.equal(await page.getByText('Started S1-02',{exact:true}).count(),0);
  assert.equal(await page.getByText('Pipeline is running',{exact:true}).count(),0,'a parked response must not announce success');
  assert.equal(await page.evaluate(()=>window.manualRunRequests),0,'Run must use the owning pipeline rather than bypassing its allowance');
  const approve=allocation.getByRole('button',{name:'Approve new allocation',exact:true});
  await approve.waitFor();
  assert.equal(await page.evaluate(()=>window.executionRequests.length),0,'reviewing an allocation cannot spend or approve it');
  await allocation.getByLabel('Reason for additional allocation').fill('Reject this allocation');
  await approve.click();
  await allocation.getByRole('alert').filter({hasText:'Allocation was rejected'}).waitFor();
  await allocation.getByText('1/2 units accepted · 6/6 attempts accounted',{exact:true}).waitFor();
  await allocation.getByLabel('Total worker attempts per unit').fill('7');
  await allocation.getByLabel('Tokens per worker').fill('300000');
  await allocation.getByLabel('Reason for additional allocation').fill('Approve remaining implementation from the saved checkpoint');
  const beforeApproval=Date.now();
  await approve.click();
  await allocation.getByRole('status').filter({hasText:'Allocation approved'}).waitFor();
  await allocation.getByText('1/2 units accepted · 7/12 attempts accounted',{exact:true}).waitFor();
  await allocation.getByText('12/600 active minutes · 320,000/3,000,000 tokens accounted, including reservations',{exact:true}).waitFor();
  const request=await page.evaluate(()=>window.executionRequests.at(-1));
  assert.equal(request.action,'budget');
  assert.equal(request.reason,'Approve remaining implementation from the saved checkpoint');
  assert.equal(request.policy.unitAttempts,7);
  assert.equal(request.policy.recoveryAttempts,4);
  assert.equal(request.policy.workerTokens,300000);
  assert.ok(request.policy.deadline>=beforeApproval+24*3600000);
  assert.equal(await allocation.getByRole('alert').count(),0);
  assert.deepEqual(errors,[]);
  console.log(`Execution visibility passed: deferred verification, delivery, exhaustion, rejected allocation and explicit approval at desktop/mobile widths. Screenshots: ${output}`);
} finally {await browser.close();}
