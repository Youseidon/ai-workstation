#!/usr/bin/env node
/**
 * Regenerates the `cursor` block of MODEL_CATALOG from the CLI itself.
 *
 * A hardcoded cursor catalog rots silently: Cursor retires ids between
 * releases, and the only symptom is `cursor-agent` exiting 1 with the whole
 * model list on stderr. `cursor-agent --list-models` is authoritative and
 * account-scoped, so re-run this after a Cursor upgrade or a plan change:
 *
 *   npm run sync:cursor-models
 *
 * Writes between the `cursor-models:start/end` markers in shared/src/index.ts
 * and touches nothing else.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const CATALOG = new URL("../shared/src/index.ts", import.meta.url);
const START = "    // <cursor-models:start> — generated by scripts/sync-cursor-models.mjs";
const END = "    // <cursor-models:end>";

/**
 * Cursor exposes no pool metadata, so this reads the only signal it does give:
 * the id prefix. Cursor brands the models it serves from its own pool with
 * `composer-`/`cursor-` (and `auto`, its router); everything else is a frontier
 * vendor model billed against that vendor.
 */
function poolFor(id) {
  return id === "auto" || id.startsWith("composer-") || id.startsWith("cursor-")
    ? "cursor"
    : "vendor";
}

/** `claude-opus-5-thinking-medium-fast` -> `opus 5 thinking medium fast`. */
function labelFor(id) {
  return id
    .replace(/^(claude|gpt|cursor)-/, "")
    .replace(/-/g, " ");
}

function parse(stdout) {
  const models = [];
  for (const line of stdout.split("\n")) {
    const match = /^([A-Za-z0-9._-]+) - (.+)$/.exec(line.trim());
    if (match === null) continue;
    const [, id, display] = match;
    models.push({ id, display, pool: poolFor(id), label: labelFor(id) });
  }
  if (models.length === 0) throw new Error("no models parsed — did the CLI output format change?");
  return models;
}

function render(models) {
  const quote = (value) => `"${value.replace(/["\\]/g, "\\$&")}"`;
  const lines = [START];
  for (const pool of ["cursor", "vendor"]) {
    const group = models.filter((model) => model.pool === pool);
    if (group.length === 0) continue;
    lines.push(`    // ${pool === "cursor" ? "Cursor's own pool" : "Frontier vendor models"} (${group.length})`);
    for (const model of group) {
      lines.push(
        `    { id: ${quote(model.id)}, label: ${quote(model.label)}, hint: ${quote(model.display)}, pool: ${quote(pool)} },`,
      );
    }
  }
  lines.push(END);
  return lines.join("\n");
}

const stdout = execFileSync("cursor-agent", ["--list-models"], { encoding: "utf8" });
const models = parse(stdout);
const source = readFileSync(CATALOG, "utf8");
const start = source.indexOf(START.trimEnd().split(" — ")[0]);
const end = source.indexOf(END);
if (start === -1 || end === -1) throw new Error("cursor-models markers not found in shared/src/index.ts");

const before = source.slice(0, start).replace(/[ \t]*$/, "");
const after = source.slice(end + END.length);
writeFileSync(CATALOG, `${before}${render(models)}${after}`);

const counts = { cursor: 0, vendor: 0 };
for (const model of models) counts[model.pool] += 1;
console.log(`wrote ${models.length} cursor models (${counts.cursor} cursor pool, ${counts.vendor} vendor pool)`);
