#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { constants } from "node:fs";
import { access, chmod, stat, writeFile } from "node:fs/promises";
import { createServer } from "node:net";
import { hostname } from "node:os";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
const defaultRoot = resolve(import.meta.dirname, "..");

function usage() {
  return `Usage: npm run setup:team-pilot -- [options]

Options:
  --server-port <port>  Backend port (default: 4100)
  --web-port <port>     Frontend port (default: 3100)
  --label <name>        Workstation label shown on Team cards
  --skip-install        Do not run npm ci
  --help                Show this help

Run this only in a fresh, separate checkout. The command refuses an existing
.env, .agent-console directory, or tracked working-tree changes.`;
}

function port(value, name) {
  const parsed = Number.parseInt(value, 10);
  if (!Number.isSafeInteger(parsed) || parsed < 1 || parsed > 65535) {
    throw new Error(`${name} must be a TCP port between 1 and 65535.`);
  }
  return parsed;
}

export function parsePilotArgs(argv) {
  const options = {
    serverPort: 4100,
    webPort: 3100,
    label: `${hostname().slice(0, 48)} team pilot`,
    install: true,
    help: false,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--help") options.help = true;
    else if (argument === "--skip-install") options.install = false;
    else if (argument === "--server-port") options.serverPort = port(argv[++index] ?? "", argument);
    else if (argument === "--web-port") options.webPort = port(argv[++index] ?? "", argument);
    else if (argument === "--label") options.label = argv[++index] ?? "";
    else throw new Error(`Unknown option: ${argument}`);
  }

  options.label = options.label.trim();
  if (options.serverPort === options.webPort) throw new Error("Server and web ports must differ.");
  if (options.label.length < 1 || options.label.length > 64 || /[\r\n]/.test(options.label)) {
    throw new Error("The workstation label must be one line between 1 and 64 characters.");
  }
  return options;
}

export function pilotEnv(options) {
  const serverUrl = `http://127.0.0.1:${options.serverPort}`;
  return `# Generated by npm run setup:team-pilot.
# This file belongs only to this isolated pilot checkout. Do not copy another
# workstation's .env or .agent-console data into this directory.

HOST=127.0.0.1
PORT=${options.serverPort}
WEB_PORT=${options.webPort}
AGENT_API_BASE_URL=${serverUrl}
NEXT_PUBLIC_AGENT_SERVER_URL=${serverUrl}
ALLOWED_ORIGINS=http://localhost:${options.webPort},http://127.0.0.1:${options.webPort}

AGENT_HOST_ACCESS=false
TASK_CONTROL_ENABLED=true
TASK_CONTROL_NOTIFICATIONS_ENABLED=false
TASK_CONTROL_REMOTE_ACTIONS_ENABLED=false
TASK_CONTROL_TRANSPORT=telegram
TASK_CONTROL_WORKSTATION_LABEL=${JSON.stringify(options.label)}
TEAM_ENABLED=false

# Create a separate bot for this pilot. Paste its token locally, never in chat.
TELEGRAM_BOT_TOKEN=
`;
}

async function exists(path) {
  try {
    await access(path, constants.F_OK);
    return true;
  } catch {
    return false;
  }
}

async function assertPortFree(value) {
  await new Promise((resolveFree, reject) => {
    const server = createServer();
    server.once("error", (error) => reject(new Error(`Port ${value} is unavailable: ${error.code ?? error.message}`)));
    server.listen(value, "127.0.0.1", () => server.close(resolveFree));
  });
}

function git(root, args) {
  return spawnSync("git", args, { cwd: root, encoding: "utf8" });
}

export async function setupTeamPilot({
  root = defaultRoot,
  options,
  checkGit = true,
  checkPorts = true,
  runInstall = options.install,
  log = console.log,
}) {
  const envPath = resolve(root, ".env");
  const statePath = resolve(root, ".agent-console");
  const nodeMajor = Number.parseInt(process.versions.node.split(".")[0] ?? "", 10);

  if (!Number.isSafeInteger(nodeMajor) || nodeMajor < 22) {
    throw new Error(`Node.js 22 or newer is required; found ${process.versions.node}.`);
  }
  const npmVersion = spawnSync("npm", ["--version"], { encoding: "utf8" });
  if (npmVersion.status !== 0) throw new Error("npm is required but was not available on PATH.");

  if (await exists(envPath)) {
    throw new Error("Refusing to replace .env. Run this command in a fresh, separate checkout.");
  }
  if (await exists(statePath)) {
    throw new Error("Refusing to reuse .agent-console. Run this command in a fresh, separate checkout.");
  }

  if (checkGit) {
    const inside = git(root, ["rev-parse", "--is-inside-work-tree"]);
    if (inside.status !== 0 || inside.stdout.trim() !== "true") throw new Error("This directory is not a Git checkout.");
    const status = git(root, ["status", "--porcelain", "--untracked-files=no"]);
    if (status.status !== 0) throw new Error("Could not inspect the Git working tree.");
    if (status.stdout.trim() !== "") throw new Error("Refusing setup because tracked files have local changes.");
  }

  if (checkPorts) {
    await assertPortFree(options.serverPort);
    await assertPortFree(options.webPort);
  }

  if (runInstall) {
    log("Installing the locked dependency tree with npm ci...");
    const install = spawnSync("npm", ["ci"], { cwd: root, stdio: "inherit" });
    if (install.status !== 0) throw new Error(`npm ci failed with exit code ${install.status ?? "unknown"}.`);
  }

  await writeFile(envPath, pilotEnv(options), { encoding: "utf8", flag: "wx", mode: 0o600 });
  await chmod(envPath, 0o600);
  const mode = (await stat(envPath)).mode & 0o777;
  if (mode !== 0o600) throw new Error(`Expected .env mode 0600, received ${mode.toString(8)}.`);

  log("");
  log("Team pilot setup complete.");
  log(`Frontend: http://localhost:${options.webPort}`);
  log(`Backend:  http://127.0.0.1:${options.serverPort}`);
  log("");
  log("Human steps still required:");
  log("1. Create a dedicated pilot bot with BotFather.");
  log("2. Set TELEGRAM_BOT_TOKEN in this checkout's .env; never paste it into chat.");
  log("3. Run: npm run dev:team-pilot");
  log("4. Pair privately on the Agents page, then enable Team for the LT-3 join test.");
  log("");
  log("Notifications, remote actions, Team, and host access remain off until explicitly enabled.");
}

async function main() {
  const options = parsePilotArgs(process.argv.slice(2));
  if (options.help) {
    console.log(usage());
    return;
  }
  await setupTeamPilot({ options });
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === resolve(scriptPath)) {
  main().catch((error) => {
    console.error(`Team pilot setup failed: ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  });
}
